from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field

class TimelineEvent(BaseModel):
    step_number: int
    elapsed_time_str: str  # e.g. "T+00m", "T+03m", "T+18m", "T+34m"
    timestamp_iso: str
    vector: str            # "CALL", "NOTIFICATION", "URL", "QR_PAYMENT", "DEEPFAKE"
    title: str
    source: str
    risk_score: int
    severity: str
    snippet: str

class ThreatCampaign(BaseModel):
    campaign_id: str = Field(..., description="Unique Threat Campaign ID generated by the correlation engine")
    threat_dna_fingerprint: str = Field(..., description="Encoded Threat DNA signature summarizing vectors, targets, and temporal span")
    correlation_status: str = Field("POSSIBLE_RELATED_ACTIVITY", description="Forensic correlation classification")
    vectors_involved: List[str] = Field(..., description="Ordered distinct attack vectors in campaign")
    event_count: int
    time_span_minutes: int
    baseline_risk_score: int = Field(..., description="Highest individual event risk score before correlation")
    escalated_risk_score: int = Field(..., description="Escalated campaign risk score reflecting multi-vector convergence")
    escalation_reason: str = Field(..., description="Explanation of why risk was escalated")
    confidence: float = Field(..., description="Correlation confidence (0.0 to 1.0)")
    correlation_evidence: List[str] = Field(..., description="Forensic points linking the events")
    timeline: List[TimelineEvent] = Field(..., description="Chronological progression of the multi-stage campaign")
    recommended_action: str = Field(..., description="Unified mitigation playbook across all vectors")
    disclaimer: str = Field(
        "Analysis represents possible related activity based on temporal clustering and shared social engineering indicators. Avoid attributing to a single attacker without confirmed network infrastructure evidence.",
        description="Forensic standard disclaimer"
    )

class SecurityEventItem(BaseModel):
    event_id: str
    event_type: str        # e.g. "CALL_SCREENED", "NOTIFICATION_INTERCEPTED", "URL_SCANNED", "QR_SCANNED"
    timestamp_iso: str
    title: str
    source: str
    risk_score: int
    severity: str
    target_brand: Optional[str] = None
    indicators: List[str] = Field(default_factory=list)
    details: Optional[Dict[str, Any]] = None

class ThreatDnaCorrelationRequest(BaseModel):
    user_id: Optional[str] = "usr_demo_12345"
    time_window_hours: int = Field(24, ge=1, le=168, description="Configurable time window in hours (e.g. 2, 6, 24, 48)")
    events: Optional[List[SecurityEventItem]] = Field(default=None, description="Optional explicit events to correlate")

class ThreatDnaCorrelationResponse(BaseModel):
    total_events_evaluated: int
    time_window_hours: int
    campaigns: List[ThreatCampaign]
    correlation_engine_version: str = "ThreatDNA-v1.0"
    summary: str
